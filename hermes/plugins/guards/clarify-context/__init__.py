"""Refuse a clarify the user cannot understand from what they have seen.

The user sees a clarify card and the visible text sent before it, never the model's reasoning. A
question such as "proceed with this plan?" whose plan was drafted only in reasoning reaches the
user as a bare question ("which plan?"). The runtime's clarify takes a per-question ``context``
that the gateway delivers, verified, before the card; this guard makes sure a question has a
subject on screen, without reading the question's wording:

* Blocked when nothing visible was sent since the user's last message and no question carries a
  ``context``. Gateway notifications (process completions) are not the user speaking, so they do
  not reset what the user has seen.
* Blocked when a reply of the current turn has ``MEDIA:`` tags in its text, unless the question's
  ``context`` carries the same files. Reply attachments are delivered only after the turn, i.e.
  after the user had to answer; in ``context`` they are delivered before the card. A reply that is
  only ``MEDIA:`` tags and delivery directives shows the user no text.

State is in memory, per session: after a restart the first clarify without context may be
refused once, which costs one retry and never shows an unexplained question.
"""

from __future__ import annotations

import logging
import os
import re
import threading
from collections import OrderedDict
from collections.abc import Mapping
from typing import Any

logger = logging.getLogger(__name__)

# Appended by the gateway to every synthetic notification turn (gateway/run_notifications.py).
_NOTIFICATION_MARK = "INTERNAL NOTIFICATION — generated by the Hermes gateway"
_MEDIA_TAG = re.compile(r"MEDIA:\s*`?([^\s`]+)`?")
# Delivery directives the gateway strips before display ([[audio_as_voice]], [[as_document]]).
_DIRECTIVE = re.compile(r"\[\[[a-z_]+\]\]")
_THINK_BLOCK = re.compile(r"<think>.*?</think>", re.S)
_FENCED = re.compile(r"```.*?```", re.S)
# Replies the gateway never shows.
_UNSHOWN = {"", "[SILENT]"}
_MAX_SESSIONS = 512

_lock = threading.Lock()
# session_id -> {"visible": seen anything since the user spoke, "media": reply MEDIA this turn}
_sessions: "OrderedDict[str, dict[str, Any]]" = OrderedDict()
_runtime_checked: bool | None = None

NO_CONTEXT = (
    "Blocked: the user has seen nothing from you since their last message, and no question has a "
    "`context`. They see only the card, never your reasoning, so a question about a plan, draft or "
    "set of options arrives without its subject. Put the material the question refers to in that "
    "question's `context` (it is delivered right before the card) and call clarify again."
)
MEDIA_IN_REPLY = (
    "Blocked: your reply text in this turn has MEDIA: tags. Reply attachments are delivered only "
    "after the turn ends, after the user would have had to answer. Put the same MEDIA: tags in the "
    "question's `context`, which is delivered (with its files) before the card, and call clarify again."
)


def _state(session_id: str) -> dict[str, Any]:
    state = _sessions.get(session_id)
    if state is None:
        state = {"visible": False, "media": set()}
        _sessions[session_id] = state
        while len(_sessions) > _MAX_SESSIONS:
            _sessions.popitem(last=False)
    else:
        _sessions.move_to_end(session_id)
    return state


def _visible_text(message: Any) -> str:
    content = getattr(message, "content", None)
    if content is None and isinstance(message, Mapping):
        content = message.get("content")
    if not isinstance(content, str):
        return ""
    return _THINK_BLOCK.sub("", content).strip()


def _runtime_supports_context() -> bool:
    """The guard asks for ``context``; a runtime whose clarify lacks it would drop the field, so
    the guard stands down there instead of blocking every question it cannot fix."""
    global _runtime_checked
    if _runtime_checked is None:
        try:
            from tools.clarify_tool import CLARIFY_SCHEMA
            items = CLARIFY_SCHEMA["parameters"]["properties"]["questions"]["items"]
            _runtime_checked = "context" in items.get("properties", {})
        except Exception:
            _runtime_checked = False
        if not _runtime_checked:
            logger.warning("clarify-context: this runtime's clarify has no `context` field; guard inactive "
                           "(is the local clarify-context patch merged?)")
    return _runtime_checked


def _on_turn_start(**kwargs: Any) -> None:
    """A turn starts: the previous turn's reply attachments have been delivered. Only the user
    speaking (not a gateway notification) resets what they have seen."""
    session_id = kwargs.get("session_id")
    if not session_id:
        return
    message = kwargs.get("user_message")
    human = not (isinstance(message, str) and _NOTIFICATION_MARK in message)
    with _lock:
        state = _state(session_id)
        state["media"] = set()
        if human:
            state["visible"] = False


def _on_response(**kwargs: Any) -> None:
    session_id = kwargs.get("session_id")
    if not session_id:
        return
    media, rest = _split_media(_visible_text(kwargs.get("assistant_message")))
    shown = _DIRECTIVE.sub("", rest).strip()
    with _lock:
        state = _state(session_id)
        state["media"] |= media
        if shown not in _UNSHOWN:
            state["visible"] = True


def _split_media(text: str) -> tuple[set[str], str]:
    """``(MEDIA paths, the remaining text)``, read the way the gateway delivers them: its own
    extractor normalizes paths (``~``, quotes, emphasis, trailing punctuation) and ignores tags in
    code, so a reply's file and the same file restated in ``context`` compare equal. The regex is
    only the fallback for a runtime without it."""
    try:
        from gateway.platforms.base import BasePlatformAdapter
        found, rest = BasePlatformAdapter.extract_media(text)
        return {os.path.normpath(path) for path, _ in found}, rest
    except Exception:
        unfenced = _FENCED.sub("", text)
        found = {os.path.normpath(os.path.expanduser(m.group(1))) for m in _MEDIA_TAG.finditer(unfenced)}
        return found, _MEDIA_TAG.sub("", text) if found else text


def _context_media(args: Mapping) -> set[str]:
    questions = args.get("questions")
    paths: set[str] = set()
    for q in questions if isinstance(questions, list) else []:
        if isinstance(q, Mapping) and isinstance(q.get("context"), str):
            paths |= _split_media(q["context"])[0]
    return paths


def _has_context(args: Mapping) -> bool:
    questions = args.get("questions")
    if not isinstance(questions, list):
        return False
    return any(isinstance(q, Mapping) and isinstance(q.get("context"), str) and q["context"].strip()
               for q in questions)


def _guard_clarify(**kwargs: Any) -> dict[str, str] | None:
    if kwargs.get("tool_name") != "clarify":
        return None
    session_id = kwargs.get("session_id")
    args = kwargs.get("args")
    if not session_id or not isinstance(args, Mapping) or not _runtime_supports_context():
        return None
    with _lock:
        state = _state(session_id)
        visible = state["visible"]
        # Files still waiting for the end of the turn, unless the question's context carries them.
        media = state["media"] - _context_media(args)
    if media:
        return {"action": "block", "message": MEDIA_IN_REPLY}
    if not visible and not _has_context(args):
        return {"action": "block", "message": NO_CONTEXT}
    return None


def register(ctx: Any) -> None:
    """Track what the user has seen per session and refuse a clarify that would arrive without it."""
    ctx.register_hook("pre_llm_call", _on_turn_start)
    ctx.register_hook("post_api_request", _on_response)
    ctx.register_hook("pre_tool_call", _guard_clarify)
