"""The replaced ``cronjob_manage``: the same tool the agent knows, with its writes routed through
the profile's ``cron.d/`` so ``jobs.json`` stays derived from manifests.

A job the agent creates becomes ``<HERMES_HOME>/cron.d/<name>/`` (``job.yaml``, and ``run.sh``
when it runs a script) and cron-sync makes the job; an update rewrites that manifest; a removal
deletes it with its job. A job whose manifest is a link into a repository (``managed.source ==
"repo"``) is tracked there and refused here. A job without a manifest marker (one made before
this plugin, by hand) can still be paused, resumed or removed, never updated: it is recreated
through a manifest instead. ``list`` and ``run`` go to the runtime untouched.

The validations the runtime's own create performs on a model-supplied job (prompt scan, script
path, delivery targets, context references) run here before anything is written.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Any, Optional

TOOL = "cronjob_manage"
ACTIONS = ("create", "list", "update", "pause", "resume", "remove", "run")
_DELEGATED = {"list", "run", "run_now", "trigger"}
_SLUG = re.compile(r"[^a-z0-9._-]+")


class ManageError(ValueError):
    """A refusal the agent gets back as the tool's error."""


def _dumps(payload: dict[str, Any]) -> str:
    return json.dumps(payload, indent=2, ensure_ascii=False)


def _error(message: str, **extra: Any) -> str:
    return _dumps({"success": False, "error": message, **extra})


def slug(text: str) -> str:
    """A directory name from a job name or label, in cron-sync's alphabet."""
    value = _SLUG.sub("-", (text or "").strip().lower()).strip("-.")
    value = re.sub(r"-{2,}", "-", value)
    return value[:50].rstrip("-.")


# ---------------------------------------------------------------------------
# run.sh for a script the agent names (a path under <home>/scripts, as the runtime takes it)
# ---------------------------------------------------------------------------

def run_script_text(rel: str) -> str:
    """Run ``<home>/scripts/<rel>`` the way the runtime's scheduler would: ``.sh``/``.bash`` with
    bash, anything else with Hermes' own Python (through the hermes-python shim, which activates
    the runtime's dependency set). The home comes from the wrapper's ``HERMES_HOME``."""
    target = f'"$HERMES_HOME/scripts/{rel}"'
    if rel.lower().endswith((".sh", ".bash")):
        command = f"exec bash {target}"
    else:
        command = f'exec "$HOME/.config/bin/hermes-python" {target}'
    return (
        "#!/bin/sh\n"
        f"# Generated by cron-manifests: the job's script is scripts/{rel} of its profile.\n"
        f'{command} "$@"\n'
    )


# ---------------------------------------------------------------------------
# From the tool's arguments to a manifest spec
# ---------------------------------------------------------------------------

def _runtime():
    from tools import cronjob_job_args as job_args
    from tools import cronjob_prompt_scan as scan
    from tools import cronjob_tools as upstream
    return upstream, job_args, scan


def _checked_script(rel: Optional[str], job_args) -> Optional[str]:
    rel = job_args._normalize_optional_job_value(rel)
    if not rel:
        return None
    error = job_args._validate_cron_script_path(rel)
    if error:
        raise ManageError(error)
    return rel


def _checked_deliver(value: Any, job_args) -> Optional[str]:
    deliver = job_args._normalize_deliver_param(value)
    error = job_args._validate_bot_chat_deliver(deliver)
    if error:
        raise ManageError(error)
    return deliver


def _checked_prompt(prompt: Optional[str], scan) -> Optional[str]:
    prompt = (prompt or "").strip()
    if not prompt:
        return None
    error = scan._scan_cron_prompt(prompt)
    if error:
        raise ManageError(error)
    return prompt


def build_spec(a: dict[str, Any], sync) -> tuple[dict[str, Any], Optional[str]]:
    """The manifest spec and run.sh text a create asks for, validated like the runtime's own
    create. ``a`` is the tool's argument dict."""
    upstream, job_args, scan = _runtime()
    if a.get("pinned"):
        raise ManageError("a job's model pin is set by hand (`hermes cron edit --pin`), never from a chat")
    schedule = (a.get("schedule") or "").strip()
    if not schedule:
        raise ManageError("schedule is required for create")
    no_agent = bool(a.get("no_agent"))
    monitor_script, monitor_url = job_args._split_monitor_arg(
        a.get("monitor"), a.get("monitor_script"), a.get("monitor_url"))
    script = _checked_script(a.get("script"), job_args)
    monitor_script = _checked_script(monitor_script, job_args)
    monitor_url = job_args._normalize_optional_job_value(monitor_url)
    if monitor_script and script:
        raise ManageError("a manifest runs one script: a monitor script or a pre-run script, not both")
    skills = job_args._canonical_skills(a.get("skill"), a.get("skills"))
    prompt = _checked_prompt(a.get("prompt"), scan)

    spec: dict[str, Any] = {"schedule": schedule}
    run_rel: Optional[str] = None
    if no_agent:
        if not script:
            raise ManageError(
                "create with no_agent=True requires a script — the script is the job. In no_agent mode "
                "the LLM is skipped entirely: prompt and skills are ignored, non-empty stdout is "
                "delivered verbatim, empty stdout sends nothing, and a non-zero exit sends an error alert.")
        if monitor_script or monitor_url:
            raise ManageError("a monitor gates an agent run; it has no place on a no_agent job")
        spec["mode"] = "no_agent"
        run_rel = script
    else:
        if not prompt and not skills:
            raise ManageError("create requires either prompt or at least one skill")
        if monitor_script or monitor_url:
            spec["mode"] = "monitor"
            if monitor_script:
                run_rel = monitor_script
            else:
                spec["monitor_url"] = monitor_url
        else:
            spec["mode"] = "prompt"
            run_rel = script
        if prompt:
            spec["prompt"] = prompt
        if skills:
            spec["skills"] = skills

    deliver = _checked_deliver(a.get("deliver"), job_args)
    origin = job_args._origin_from_env(schedule)
    deliver = job_args._resolve_cron_context_deliver(deliver)
    if deliver is None:
        deliver = "origin" if origin else "local"
    spec["deliver"] = deliver
    if origin:
        spec["origin"] = origin
    failure = job_args._resolve_cron_context_deliver(_checked_deliver(a.get("failure_deliver"), job_args))
    if failure:
        spec["failure_deliver"] = failure
    if a.get("repeat") is not None:
        spec["repeat"] = int(a["repeat"])
    workdir = job_args._normalize_optional_job_value(a.get("workdir"))
    if workdir:
        spec["workdir"] = workdir
    if not no_agent:
        context_from = a.get("context_from")
        if a.get("continuity") is not None:
            context_from = job_args._apply_continuity(context_from, bool(a["continuity"]))
        refs = job_args._clean_str_list(context_from)
        if refs:
            error = job_args._validate_context_from_refs(refs)
            if error:
                raise ManageError(error)
            spec["context_from"] = refs
        if a.get("enabled_toolsets") is not None:
            spec["enabled_toolsets"] = job_args._clean_str_list(a["enabled_toolsets"])
        if a.get("attach_to_session") is not None:
            spec["attach_to_session"] = bool(a["attach_to_session"])
    if a.get("paused"):
        spec["paused"] = True
    return spec, (run_script_text(run_rel) if run_rel else None)


def _name_for(a: dict[str, Any], spec: dict[str, Any], sync) -> str:
    label = a.get("name") or spec.get("prompt") or (spec.get("skills") or [None])[0] or ""
    name = slug(str(label))
    if not name or not sync.NAME_RE.match(name):
        raise ManageError(
            "give the job a `name` cron-sync can use as a directory: lowercase letters, digits, `.`, `_`, `-`")
    return name


# ---------------------------------------------------------------------------
# Actions
# ---------------------------------------------------------------------------

def _job_for(name: str, home: Path, sync) -> Optional[dict[str, Any]]:
    def run(jobs_api):
        for job in jobs_api.load_jobs():
            marker = job.get(sync.MARKER)
            if isinstance(marker, dict) and marker.get("manifest") == name:
                return job
        return None
    return sync._with_home(home, run)


def _format(job: dict[str, Any], job_args) -> dict[str, Any]:
    try:
        return job_args._format_job(job)
    except Exception:  # noqa: BLE001 — a formatting helper the runtime may rename
        return job


def _liveness(job_args) -> dict[str, Any]:
    try:
        return job_args._gateway_liveness_notice()
    except Exception:  # noqa: BLE001
        return {}


def create(a: dict[str, Any], home: Path, sync) -> str:
    upstream, job_args, _scan = _runtime()
    spec, run_text = build_spec(a, sync)
    name = _name_for(a, spec, sync)
    try:
        directory = sync.write_local(home, name, spec, run_text)
    except sync.ManifestError as exc:
        raise ManageError(str(exc)) from exc
    plan, _done = sync.sync_home(home, check=False, prune=False)
    job = _job_for(name, home, sync)
    if plan.failed() or job is None:
        sync.remove_local(home, name)
        raise ManageError("; ".join(plan.errors + plan.conflicts) or f"{name}: the sync made no job")
    upstream._notify_provider_jobs_changed_safe()
    message = f"Cron job '{name}' created as {sync.MANIFEST_DIR}/{name}/."
    if not job.get("enabled", True):
        message += " Created PAUSED — resume to schedule, or explicitly run now."
    return _dumps({
        "success": True, "job_id": job["id"], "name": name, "skills": job.get("skills", []),
        "schedule": job.get("schedule_display"), "deliver": job.get("deliver", "local"),
        "next_run_at": job.get("next_run_at"), "job": _format(job, job_args), "manifest": str(directory),
        "message": message, **_liveness(job_args),
    })


def _merge_update(spec: dict[str, Any], run_text: Optional[str], a: dict[str, Any],
                  sync) -> tuple[dict[str, Any], Optional[str]]:
    """The manifest after the tool's update arguments: '' and [] clear, None leaves alone."""
    _upstream, job_args, scan = _runtime()
    spec = dict(spec)
    if a.get("pinned"):
        raise ManageError("a job's model pin is set by hand (`hermes cron edit --pin`), never from a chat")
    if a.get("name") is not None and slug(a["name"]) != spec.get("_name"):
        raise ManageError("a job is its directory: to rename it, remove it and create it again")
    if a.get("schedule"):
        spec["schedule"] = a["schedule"].strip()
    if a.get("prompt") is not None:
        prompt = _checked_prompt(a["prompt"], scan)
        spec.pop("prompt", None)
        if prompt:
            spec["prompt"] = prompt
    if a.get("skills") is not None or a.get("skill") is not None:
        skills = job_args._canonical_skills(a.get("skill"), a.get("skills"))
        spec.pop("skills", None)
        if skills:
            spec["skills"] = skills
    if a.get("no_agent") is not None:
        spec["mode"] = "no_agent" if a["no_agent"] else ("monitor" if spec["mode"] == "monitor" else "prompt")
    monitor_script, monitor_url = job_args._split_monitor_arg(
        a.get("monitor"), a.get("monitor_script"), a.get("monitor_url"))
    if monitor_script is not None or monitor_url is not None:
        spec.pop("monitor_url", None)
        if monitor_script:
            run_text = run_script_text(_checked_script(monitor_script, job_args))
            spec["mode"] = "monitor"
        elif monitor_url:
            run_text = None
            spec["monitor_url"] = monitor_url.strip()
            spec["mode"] = "monitor"
        elif spec["mode"] == "monitor":
            run_text = None
            spec["mode"] = "prompt"
    if a.get("script") is not None:
        rel = _checked_script(a["script"], job_args)
        run_text = run_script_text(rel) if rel else None
    for key in ("deliver", "failure_deliver"):
        if a.get(key) is not None:
            value = job_args._resolve_cron_context_deliver(_checked_deliver(a[key], job_args))
            spec.pop(key, None)
            if value:
                spec[key] = value
    if a.get("repeat") is not None:
        spec["repeat"] = int(a["repeat"])
    if a.get("workdir") is not None:
        spec.pop("workdir", None)
        if a["workdir"].strip():
            spec["workdir"] = a["workdir"].strip()
    if a.get("context_from") is not None or a.get("continuity") is not None:
        refs = a.get("context_from") if a.get("context_from") is not None else spec.get("context_from")
        if a.get("continuity") is not None:
            refs = job_args._apply_continuity(refs, bool(a["continuity"]))
        refs = job_args._clean_str_list(refs)
        spec.pop("context_from", None)
        if refs:
            error = job_args._validate_context_from_refs(refs)
            if error:
                raise ManageError(error)
            spec["context_from"] = refs
    if a.get("enabled_toolsets") is not None:
        spec["enabled_toolsets"] = job_args._clean_str_list(a["enabled_toolsets"])
    if a.get("attach_to_session") is not None:
        spec["attach_to_session"] = bool(a["attach_to_session"])
    if spec["mode"] == "no_agent":
        for key in ("prompt", "skills", "monitor_url", "context_from", "enabled_toolsets", "attach_to_session"):
            spec.pop(key, None)
    spec.pop("_name", None)
    return spec, run_text


def update(job: dict[str, Any], a: dict[str, Any], home: Path, sync) -> str:
    upstream, job_args, _scan = _runtime()
    name = job[sync.MARKER]["manifest"]
    directory = home / sync.MANIFEST_DIR / name
    manifest_file = directory / sync.MANIFEST_FILE
    run_file = directory / sync.RUN_SCRIPT
    old_spec = sync.yaml.safe_load(manifest_file.read_text(encoding="utf-8")) or {}
    old_run = run_file.read_text(encoding="utf-8") if run_file.is_file() else None
    spec, run_text = _merge_update({**old_spec, "_name": name}, old_run, a, sync)
    if spec == old_spec and run_text == old_run:
        raise ManageError("No updates provided.")
    manifest_file.write_text(sync.yaml.safe_dump(spec, sort_keys=False, allow_unicode=True), encoding="utf-8")
    if run_text is None and run_file.exists():
        run_file.unlink()
    elif run_text is not None:
        run_file.write_text(run_text, encoding="utf-8")
        run_file.chmod(0o755)
    try:
        sync.load_manifest(directory)
    except sync.ManifestError as exc:
        manifest_file.write_text(sync.yaml.safe_dump(old_spec, sort_keys=False, allow_unicode=True),
                                 encoding="utf-8")
        if old_run is None:
            run_file.unlink(missing_ok=True)
        else:
            run_file.write_text(old_run, encoding="utf-8")
            run_file.chmod(0o755)
        raise ManageError(str(exc)) from exc
    plan, _done = sync.sync_home(home, check=False, prune=False)
    if plan.failed():
        raise ManageError("; ".join(plan.errors + plan.conflicts))
    upstream._notify_provider_jobs_changed_safe()
    updated = _job_for(name, home, sync) or job
    return _dumps({"success": True, "job": _format(updated, job_args), "manifest": str(directory)})


def remove(job: dict[str, Any], home: Path, sync) -> str:
    upstream, _job_args, _scan = _runtime()
    name = job[sync.MARKER]["manifest"]
    try:
        sync.drop_local(home, name)
    except sync.ManifestError as exc:
        raise ManageError(str(exc)) from exc
    upstream._notify_provider_jobs_changed_safe()
    return _dumps({
        "success": True, "message": f"Cron job '{job['name']}' removed with {sync.MANIFEST_DIR}/{name}/.",
        "removed_job": {"id": job["id"], "name": job["name"], "schedule": job.get("schedule_display")},
    })


def _source(job: dict[str, Any], sync) -> Optional[str]:
    marker = job.get(sync.MARKER)
    return marker.get("source") if isinstance(marker, dict) else None


def handle(args: dict[str, Any], home: Path, sync, **kw: Any) -> str:
    """The tool handler's body: ``args`` is the model's argument dict, ``home`` the profile."""
    upstream, _job_args, _scan = _runtime()
    action = str(args.get("action") or "").strip().lower()
    try:
        if action in _DELEGATED:
            return upstream._cronjob_handler(args, **kw)
        if action == "create":
            return create(args, home, sync)
        if action not in ("update", "pause", "resume", "remove"):
            return _error(f"Unknown cron action '{args.get('action')}'")
        job_id = args.get("job_id")
        if not job_id:
            return _error(f"job_id is required for action '{action}'")
        job, error = upstream._resolve_job_or_error(job_id)
        if error is not None:
            return error
        source = _source(job, sync)
        if source == "repo":
            return _error(
                f"'{job['name']}' is tracked in a repository ({sync.MANIFEST_DIR}/{job[sync.MARKER]['manifest']}/ "
                "is a link): change its job.yaml there and run install.sh. Tell the user instead of working around it.")
        if action == "update":
            if source != "local":
                return _error(
                    f"'{job['name']}' has no manifest (it was created by hand before jobs lived in "
                    f"{sync.MANIFEST_DIR}/): remove it and create it again, which makes one.")
            return update(job, args, home, sync)
        if action == "remove" and source == "local":
            return remove(job, home, sync)
        return upstream._cronjob_handler(args, **kw)
    except ManageError as exc:
        return _error(str(exc))
    except Exception as exc:  # noqa: BLE001 — a tool never raises into the agent
        return _error(f"{TOOL}: {type(exc).__name__}: {exc}")


def load_sync(hermes_root: Path):
    """cron-sync.py, the engine every write goes through, by path (it is a script, not a package)."""
    import importlib.util
    name = "hermes_cron_sync"
    if name not in sys.modules:
        spec = importlib.util.spec_from_file_location(name, hermes_root / "scripts" / "cron-sync.py")
        module = importlib.util.module_from_spec(spec)
        sys.modules[name] = module
        spec.loader.exec_module(module)
    return sys.modules[name]
